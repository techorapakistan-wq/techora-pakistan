create table if not exists public.site_analytics (
  id bigint generated by default as identity primary key,
  session_id uuid not null,
  event_type text not null check (event_type in ('page_view', 'product_view')),
  path text not null check (char_length(path) between 1 and 300),
  product_id text,
  product_name text,
  created_at timestamptz not null default now()
);

create index if not exists site_analytics_created_at_idx
  on public.site_analytics (created_at desc);
create index if not exists site_analytics_session_id_idx
  on public.site_analytics (session_id, created_at desc);
create index if not exists site_analytics_product_name_idx
  on public.site_analytics (product_name, created_at desc)
  where event_type = 'product_view';

alter table public.site_analytics enable row level security;

grant insert on public.site_analytics to anon, authenticated;
grant select on public.site_analytics to authenticated;
grant usage, select on sequence public.site_analytics_id_seq to anon, authenticated;

drop policy if exists "Public can record storefront views" on public.site_analytics;
create policy "Public can record storefront views"
  on public.site_analytics
  for insert
  to anon, authenticated
  with check (
    session_id is not null
    and event_type in ('page_view', 'product_view')
    and char_length(path) between 1 and 300
    and (product_name is null or char_length(product_name) <= 200)
  );

drop policy if exists "Admins can view storefront analytics" on public.site_analytics;
create policy "Admins can view storefront analytics"
  on public.site_analytics
  for select
  to authenticated
  using (public.is_admin());
